}

extern "C" int32_t ignis_device_sync(struct ignis_device *d) {
  if (d == nullptr) {
    return -1;
  }
  if (!ensure_device(d)) {
    return -1;
  }
  cudaError_t err = cudaEventRecord(d->blocking_sync, d->load_stream);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaEventRecord", err);
  }
  // The blocking-sync event sleeps (no CPU spin) until the stream drains.
  err = cudaEventSynchronize(d->blocking_sync);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaEventSynchronize", err);
  }
  return 0;
}

extern "C" int32_t ignis_device_driver_version(int32_t *version) {
  if (version == nullptr) {
    return -1;
  }
  // The runtime loads the driver's library here, if there is one; with none
  // it reports version 0 (GitHub #329). No context is created.
  int driver_version = 0;
  cudaError_t err = cudaDriverGetVersion(&driver_version);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaDriverGetVersion", err);
  }
  *version = driver_version;
  return 0;
}

extern "C" int32_t ignis_device_runtime_version(int32_t *version) {
  if (version == nullptr) {
    return -1;
  }
  int runtime_version = 0;
  cudaError_t err = cudaRuntimeGetVersion(&runtime_version);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaRuntimeGetVersion", err);
  }
  *version = runtime_version;
  return 0;
}

extern "C" int32_t ignis_device_nvml_mem_info(int device_id, uint64_t *free_bytes,
                                              uint64_t *total_bytes) {
  if (free_bytes == nullptr || total_bytes == nullptr) {
    return -1;
  }
  nvmlMemory_t memory{};
  if (on_nvml_device(device_id, "nvmlDeviceGetMemoryInfo", [&](const Nvml *api, nvmlDevice_t device) {
        return api->memory_info(device, &memory);
      }) != 0) {
    return -1;
  }
  *free_bytes = memory.free;
  *total_bytes = memory.total;
  return 0;
}

extern "C" int32_t ignis_device_nvml_process_bytes(int device_id, uint32_t pid, uint64_t *bytes) {
  if (bytes == nullptr) {
    return -1;
  }
  bool reported = false;
  bool unavailable = false;
  uint64_t held = 0;
  if (on_nvml_device(device_id, "nvmlDeviceGetComputeRunningProcesses_v3",
                     [&](const Nvml *api, nvmlDevice_t device) -> nvmlReturn_t {
        if (api->compute_processes == nullptr) {
          return NVML_SUCCESS;  // a driver without the query: no figure
        }
        std::vector<nvmlProcessInfo_t> processes;
        unsigned int count = 0;
        nvmlReturn_t rc = api->compute_processes(device, &count, nullptr);
        // A process can start between the two calls: ask again with room to spare.
        for (int attempt = 0; rc == NVML_ERROR_INSUFFICIENT_SIZE && attempt < 3; ++attempt) {
          processes.resize(count + 8);
          count = static_cast<unsigned int>(processes.size());
          rc = api->compute_processes(device, &count, processes.data());
        }
        if (rc == NVML_ERROR_NOT_SUPPORTED) {
          return NVML_SUCCESS;  // no figure, and not an error
        }
        if (rc != NVML_SUCCESS) {
          return rc;
        }
        for (unsigned int i = 0; i < count && i < processes.size(); ++i) {
          if (processes[i].pid != pid) {
            continue;
          }
          if (processes[i].usedGpuMemory == static_cast<unsigned long long>(NVML_VALUE_NOT_AVAILABLE)) {
            unavailable = true;
          } else {
            reported = true;
            held += processes[i].usedGpuMemory;
          }
        }
        return NVML_SUCCESS;
      }) != 0) {
    return -1;
  }
  if (!reported || unavailable) {
    return 1;
  }
  *bytes = held;
  return 0;
}

extern "C" int32_t ignis_device_identity(int device_id, char *name, uint32_t name_bytes, int32_t *major,
                                         int32_t *minor) {
  if (name == nullptr || name_bytes == 0 || major == nullptr || minor == nullptr) {
    return -1;
  }
  // The compute capability as the CUDA runtime reports it: an attribute query,
  // which creates no context.
  int cc_major = 0;
  int cc_minor = 0;
  cudaError_t err = cudaDeviceGetAttribute(&cc_major, cudaDevAttrComputeCapabilityMajor, device_id);
  if (err == cudaSuccess) {
    err = cudaDeviceGetAttribute(&cc_minor, cudaDevAttrComputeCapabilityMinor, device_id);
  }
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaDeviceGetAttribute", err);
  }
  name[0] = '\0';
  if (on_nvml_device(device_id, "nvmlDeviceGetName", [&](const Nvml *api, nvmlDevice_t device) {
        return api->name(device, name, name_bytes);
      }) != 0) {
    return -1;
  }
  name[name_bytes - 1] = '\0';
  *major = cc_major;
  *minor = cc_minor;
  return 0;
}

extern "C" const char *ignis_build_cuda_architectures(void) { return IGNIS_BUILD_CUDA_ARCHITECTURES; }

extern "C" int32_t ignis_device_mem_info(struct ignis_device *d, uint64_t *free_bytes,
                                         uint64_t *total_bytes) {
  if (d == nullptr || free_bytes == nullptr || total_bytes == nullptr) {
    return -1;
  }
  if (!ensure_device(d)) {
    return -1;
  }
  size_t free_sz = 0;
  size_t total_sz = 0;
  cudaError_t err = cudaMemGetInfo(&free_sz, &total_sz);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaMemGetInfo", err);
  }
  *free_bytes = static_cast<uint64_t>(free_sz);
  *total_bytes = static_cast<uint64_t>(total_sz);
  return 0;
}

extern "C" void ignis_device_free(struct ignis_device *d, void *ptr) {
  if (d == nullptr || ptr == nullptr) {
    return;
  }
  if (!ensure_device(d)) {
    return;
  }
  ignis_alloc_count_record(IGNIS_ALLOC_DEVICE, false, 0);
  cudaError_t err = cudaFree(ptr);
  if (err != cudaSuccess) {
    log_cuda_error(0, "cudaFree", err);
  }
}

// ADR 0062: the 27B's token embedding, read by the gather in place over the
// bus. Mapped for the device pointer, portable so any context reads it (the
// Flash-Next expert pool's flags, residency.cu).
extern "C" int32_t ignis_device_host_alloc_mapped(struct ignis_device *d, uint64_t bytes,
                                                  void **out_host, void **out_device) {
  if (d == nullptr || out_host == nullptr || out_device == nullptr || bytes == 0) {
    return -1;
  }
  if (!ensure_device(d)) {
    return -1;
  }
  void *host = nullptr;
  cudaError_t err = cudaHostAlloc(&host, static_cast<std::size_t>(bytes),
                                  cudaHostAllocMapped | cudaHostAllocPortable);
  if (err != cudaSuccess) {
    return log_cuda_error(-1, "cudaHostAlloc(mapped)", err);
  }
  void *device = nullptr;
  err = cudaHostGetDevicePointer(&device, host, 0);
  if (err != cudaSuccess) {
    cudaFreeHost(host);
    return log_cuda_error(-1, "cudaHostGetDevicePointer", err);
  }
  *out_host = host;
  *out_device = device;
  return 0;
}

extern "C" void ignis_device_host_free(struct ignis_device *d, void *host) {
  if (d == nullptr || host == nullptr) {
    return;
  }
  if (!ensure_device(d)) {
    return;
  }
  cudaError_t err = cudaFreeHost(host);
  if (err != cudaSuccess) {
    log_cuda_error(0, "cudaFreeHost", err);
  }
}

extern "C" void ignis_device_destroy(struct ignis_device *d) {
  if (d == nullptr) {
    return;
  }
  if (ensure_device(d)) {
    // Drain the load stream before destroying it (frees any pending work).
    cudaStreamSynchronize(d->load_stream);
    cudaEventDestroy(d->blocking_sync);
    cudaStreamDestroy(d->load_stream);
  }
  std::free(d);
}